  function normalizeMissionText(text) {
    return String(text)
      .replace(/\r\n/g, "\n")
      .split("\n")
      .map((line) => line.replace(/[ \t]+$/g, ""))
      .join("\n")
      .trim();
  }

  function randomFromText(text, salt) {
    const seed = cyrb128(`${salt}:${text}`);
    return sfc32(seed[0], seed[1], seed[2], seed[3]);
  }

  function cyrb128(input) {
    let h1 = 1779033703;
    let h2 = 3144134277;
    let h3 = 1013904242;
    let h4 = 2773480762;
    for (let index = 0; index < input.length; index += 1) {
      const code = input.charCodeAt(index);
      h1 = h2 ^ Math.imul(h1 ^ code, 597399067);
      h2 = h3 ^ Math.imul(h2 ^ code, 2869860233);
      h3 = h4 ^ Math.imul(h3 ^ code, 951274213);
      h4 = h1 ^ Math.imul(h4 ^ code, 2716044179);
    }
    h1 = Math.imul(h3 ^ (h1 >>> 18), 597399067);
    h2 = Math.imul(h4 ^ (h2 >>> 22), 2869860233);
    h3 = Math.imul(h1 ^ (h3 >>> 17), 951274213);
    h4 = Math.imul(h2 ^ (h4 >>> 19), 2716044179);
    return [(h1 ^ h2 ^ h3 ^ h4) >>> 0, (h2 ^ h1) >>> 0, (h3 ^ h1) >>> 0, (h4 ^ h1) >>> 0];
  }

  function sfc32(a, b, c, d) {
    return function next() {
      a >>>= 0;
      b >>>= 0;
      c >>>= 0;
      d >>>= 0;
      const t = (a + b) | 0;
      a = b ^ (b >>> 9);
      b = (c + (c << 3)) | 0;
      c = (c << 21) | (c >>> 11);
      d = (d + 1) | 0;
      const result = (t + d) | 0;
      c = (c + result) | 0;
      return (result >>> 0) / 4294967296;
    };
  }

  function renderMarkdown(markdown) {
    const lines = normalizeMissionText(markdown).split("\n");
    const html = [];
    let paragraph = [];
    let list = null;

    function flushParagraph() {
      if (!paragraph.length) {
        return;
      }
      html.push(`<p>${inlineFormat(paragraph.join(" "))}</p>`);
      paragraph = [];
    }

    function flushList() {
      if (!list) {
        return;
      }
      html.push(`</${list}>`);
      list = null;
    }

    function ensureList(type) {
      flushParagraph();
      if (list && list !== type) {
        flushList();
      }
      if (!list) {
        list = type;
        html.push(`<${type}>`);
      }
    }

    for (const rawLine of lines) {
      const line = rawLine.trim();
      if (!line) {
        flushParagraph();
        flushList();
        continue;
      }

      const h1 = /^\*\*(.+)\*\*$/.exec(line);
      if (h1) {
        flushParagraph();
        flushList();
        html.push(`<h1>${inlineFormat(h1[1])}</h1>`);
        continue;
      }

      const h2 = /^\*([^*]+)\*\s*-\s*(.*)$/.exec(line);
      if (h2) {
        flushParagraph();
        flushList();
        html.push(`<h2>${inlineFormat(h2[1])}</h2>`);
        if (h2[2]) {
          paragraph.push(h2[2]);
        }
        continue;
      }

      if (isStandaloneHeading(line)) {
        flushParagraph();
        flushList();
        html.push(`<h3>${inlineFormat(line)}</h3>`);
        continue;
      }

      const ordered = /^(\d+)\.\s+(.+)$/.exec(line);
      if (ordered) {
        ensureList("ol");
        html.push(`<li>${inlineFormat(ordered[2])}</li>`);
        continue;
      }

      const unordered = /^-\s+(.+)$/.exec(line);
      if (unordered) {
        ensureList("ul");
        html.push(`<li>${inlineFormat(unordered[1])}</li>`);
        continue;
      }

      flushList();
      paragraph.push(line);
    }

    flushParagraph();
    flushList();
    return html.join("\n");
  }

  function isStandaloneHeading(line) {
    return /^(Normal Missions|Spy Missions \(.*\)|Alternative Missions \(.*\)|Locations|Bureacracies|Excuses \(Information\)|Equipment Denial|Clerks|Clues|Evidence|Rumors \(.*\))\s*:?$/.test(line);
  }

  function inlineFormat(value) {
    return inlineFormatEscaped(escapeHtml(value));
  }

  function inlineFormatEscaped(value) {
    return value
      .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
      .replace(/\*([^*]+)\*/g, "<em>$1</em>");
  }

  function escapeHtml(value) {
    return String(value)
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;");
  }

